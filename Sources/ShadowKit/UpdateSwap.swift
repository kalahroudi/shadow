import Foundation

/// The external swap (R11, R12). The running app never replaces its own bundle: it writes this script, starts it
/// detached and quits. The script waits for the old process, swaps the bundles, opens the new app and then either
/// deletes the previous copy (marker seen) or rolls back (no marker in time).
public struct UpdateSwap: Sendable {
    public static let waitSeconds = 30
    public static let confirmSeconds = 40

    public let installedApp: URL
    public let stagedApp: URL
    public let paths: AppPaths
    /// `open` in production; tests pass a stub.
    public let opener: String
    public let waitSeconds: Int
    public let confirmSeconds: Int

    public init(installedApp: URL, stagedApp: URL, paths: AppPaths, opener: String = "/usr/bin/open",
                waitSeconds: Int = UpdateSwap.waitSeconds, confirmSeconds: Int = UpdateSwap.confirmSeconds) {
        self.installedApp = installedApp; self.stagedApp = stagedApp; self.paths = paths; self.opener = opener
        self.waitSeconds = waitSeconds; self.confirmSeconds = confirmSeconds
    }

    /// `Shadow.app` becomes `Shadow.previous.app` next to it.
    public var previousApp: URL {
        installedApp.deletingLastPathComponent()
            .appendingPathComponent(installedApp.deletingPathExtension().lastPathComponent + ".previous.app", isDirectory: true)
    }
    public var scriptURL: URL { paths.updatesDir.appendingPathComponent("swap.sh") }

    /// Paths and limits are passed as arguments, not spliced into the text, so no quoting can go wrong.
    func arguments(pid: Int32) -> [String] {
        [scriptURL.path, String(pid), installedApp.path, previousApp.path, stagedApp.path,
         paths.updateOKFile.path, paths.updateFailedFile.path, opener, String(waitSeconds), String(confirmSeconds)]
    }

    /// A `/bin/sh` process ready to run. Not started, so tests can run it and wait.
    public func makeProcess(pid: Int32) throws -> Process {
        try FileManager.default.createDirectory(at: paths.updatesDir, withIntermediateDirectories: true)
        try Data(Self.script.utf8).write(to: scriptURL, options: .atomic)
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/bin/sh")
        p.arguments = arguments(pid: pid)
        p.standardInput = FileHandle.nullDevice
        p.standardOutput = FileHandle.nullDevice
        p.standardError = FileHandle.nullDevice
        return p
    }

    /// Records the target version, then starts the script detached. The caller quits the app right after.
    public func launch(version: String, pid: Int32 = ProcessInfo.processInfo.processIdentifier) throws {
        let process = try makeProcess(pid: pid)
        try Data(version.utf8).write(to: paths.updatePendingFile, options: .atomic)
        try process.run()
    }

    // Ticks of 0.1 s so the 30 s and 40 s limits are exact enough and tests can use one-second limits.
    static let script = """
    #!/bin/sh
    # Generated by Shadow. Args: pid app previous staged ok failed opener wait confirm
    trap '' HUP
    pid=$1; app=$2; prev=$3; staged=$4; ok=$5; failed=$6; opener=$7; wait_s=$8; confirm_s=$9

    fail() {
      printf '%s\\n' "$1" > "$failed"
      "$opener" "$app"
      exit 1
    }

    # 1. wait for the old process to exit, force-killing it after the limit
    ticks=0
    while kill -0 "$pid" 2>/dev/null; do
      if [ "$ticks" -ge $((wait_s * 10)) ]; then kill -9 "$pid" 2>/dev/null; sleep 0.5; break; fi
      sleep 0.1; ticks=$((ticks + 1))
    done

    # 2. swap: old -> previous, staged -> app, restoring the old one if either move fails
    rm -rf "$prev"
    mv "$app" "$prev" || fail "the installed app could not be moved aside"
    if ! mv "$staged" "$app"; then
      rm -rf "$app"
      mv "$prev" "$app"
      fail "the new app could not be moved into place"
    fi
    rm -f "$ok"
    "$opener" "$app"

    # 3. wait for the new app to confirm it started
    ticks=0
    while [ ! -e "$ok" ]; do
      if [ "$ticks" -ge $((confirm_s * 10)) ]; then
        pkill -f "$app/Contents/MacOS/" 2>/dev/null
        sleep 1
        rm -rf "$app"
        mv "$prev" "$app"
        fail "the new version did not confirm it started within $confirm_s seconds"
      fi
      sleep 0.1; ticks=$((ticks + 1))
    done
    rm -rf "$prev"
    """
}

/// The new app's half of the hand-off, and what the next start does about it (R12, R13).
public enum UpdateHandoff {
    /// Writes the `update-ok` marker after `delay`, only if the app is still running. One-shot, no timer.
    public static func confirmLaunch(paths: AppPaths, delay: Duration = .seconds(4), isAlive: @Sendable () -> Bool = { true },
                                     sleep: @Sendable (Duration) async -> Void = { try? await Task.sleep(for: $0) }) async {
        await sleep(delay)
        guard !Task.isCancelled, isAlive() else { return }
        try? FileManager.default.createDirectory(at: paths.root, withIntermediateDirectories: true)
        try? Data().write(to: paths.updateOKFile, options: .atomic)
    }

    public enum Notice: Equatable, Sendable {
        case updated(String)
        case rolledBack(String)

        public var text: String {
            switch self {
            case .updated(let v): return "Updated to \(v)"
            case .rolledBack(let why): return "The update didn't work, so Shadow went back to the previous version. \(why)"
            }
        }
    }

    /// Removes leftover staging and swap files, then reports the outcome of the last update once.
    /// The rollback reason is scrubbed because it comes from a file and may contain paths.
    @discardableResult
    public static func cleanup(paths: AppPaths, currentVersion: String,
                               home: String = NSHomeDirectory(), user: String = NSUserName()) -> Notice? {
        let fm = FileManager.default
        try? fm.removeItem(at: paths.updatesDir)
        defer { try? fm.removeItem(at: paths.updatePendingFile); try? fm.removeItem(at: paths.updateFailedFile) }

        if let raw = try? String(contentsOf: paths.updateFailedFile, encoding: .utf8) {
            let reason = LogScrubber.scrub(raw.trimmingCharacters(in: .whitespacesAndNewlines), home: home, user: user)
            return .rolledBack(reason.isEmpty ? "No reason was recorded." : reason)
        }
        if let raw = try? String(contentsOf: paths.updatePendingFile, encoding: .utf8) {
            let target = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if !target.isEmpty, target == currentVersion { return .updated(target) }
        }
        return nil
    }
}
